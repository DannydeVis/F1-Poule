-- ------------------------------------------------------------
--  Controle
--  Hieronder moet overal 'ok' staan.
--
--  Als view en niet als losse select onderaan dit bestand. Twee redenen.
--  Je kunt hem voortaan op elk moment opvragen -- `select * from
--  poule_controle;` -- in plaats van het hele schema opnieuw te moeten
--  draaien om te zien hoe je database ervoor staat. En belangrijker: een
--  view is te bevragen vanuit een test, en deze regels waren stilletjes
--  verouderd (ze telden negen vragen toen er veertien stonden en twee
--  handmatig-vlaggen toen er zeven waren). Zie test/controle.test.sql.
-- ------------------------------------------------------------

-- Het seizoen waar de controletabel over gaat. Stond overal vast op 2026, en
-- in januari 2027 had de tabel dan vrolijk "seizoen 2026 rond: ok" gezegd over
-- een seizoen dat niemand meer speelt, terwijl de kalender van 2027 ontbrak.
--
-- Het eerste seizoen met een race die nog niets heeft: nog te rijden, of
-- blijven hangen. Dat tweede telt mee met opzet -- een race die in december
-- blijft hangen hoort in de tabel te blijven staan, ook als de kalender van
-- volgend jaar er al is. Is alles gereden, dan het laatste seizoen dat er is.
create or replace function public.controle_seizoen()
returns int
language sql
stable
set search_path = public
as $$
  select coalesce(
    (select min(season) from public.races
      where not afgelast
        and race_result is null and quali_result is null and sprint_result is null),
    (select max(season) from public.races),
    extract(year from now())::int)
$$;

drop view if exists public.poule_controle;
create view public.poule_controle as
-- Niet alleen "bestaat hij", maar ook "vuurt hij op alle drie". Deze trigger
-- stond lang op `insert or update`, en dan kon je een antwoord dat vastligt
-- verwijderen en opnieuw invoeren -- de regel omzeild zonder hem te breken.
-- Een controle die dat niet ziet zegt 'ok' over een half dichte deur.
--
-- tgtype is een bitmasker: 4 = insert, 8 = delete, 16 = update.
select 'deadline-trigger op answers' as controle,
       case
         when not exists (
           select 1 from pg_trigger
           where tgrelid = 'public.answers'::regclass
             and tgname = 'answers_deadline') then 'ONTBREEKT'
         when exists (
           select 1 from pg_trigger
           where tgrelid = 'public.answers'::regclass
             and tgname = 'answers_deadline'
             and (tgtype & 4) > 0 and (tgtype & 16) > 0 and (tgtype & 8) > 0) then 'ok'
         else 'ZONDER DELETE — draai schema.sql opnieuw' end as uitkomst
union all
-- De jokergrens zit sinds kort in de database en niet meer in de app, en dat
-- is precies het soort wijziging waarvan je wilt weten of hij bij jou ook
-- geland is. Zonder deze regels stond er in de controletabel niets over, en
-- kon een uitdraai je dus niet vertellen of je schema.sql-run gelukt was.
--
-- De kolom zelf krijgt geen eigen regel: de tweede regel hieronder telt erop,
-- dus zonder die kolom bestaat deze view niet eens en zou zo'n regel altijd
-- 'ok' zeggen. Wat wél los kan ontbreken is de grens eromheen en de bewaking
-- die verlagen tegenhoudt, en daar gaat het hier dan ook over.
select 'jokeraantal: grens en bewaking',
       case
         when not exists (
           select 1 from pg_constraint
           where conrelid = 'public.pools'::regclass
             and conname = 'pools_jokers_aantal') then 'GRENS 1-5 ONTBREEKT — draai schema.sql opnieuw'
         when not exists (
           select 1 from pg_trigger
           where tgrelid = 'public.pools'::regclass
             and tgname = 'pools_jokeraantal') then 'ZONDER BEWAKING — draai schema.sql opnieuw'
         else 'ok' end
union all
-- Vijf is de standaard. Dit getal zegt of iemand er bewust van afgeweken is.
select 'poules met een eigen jokeraantal',
       (select count(*)::text from public.pools where jokers_aantal <> 5)
union all
select 'aantal poules',        (select count(*)::text from public.pools)
union all
select 'aantal spelers',       (select count(*)::text from public.pool_members)
union all
-- Het getal om in de gaten te houden na het dichtzetten van de policies.
-- Deze spelers hangen nog aan geen enkel account, en hun antwoorden staan
-- daarom nog open voor iedereen die de poulecode heeft. Elke keer dat zo
-- iemand de app opent claimt hij zichzelf en zakt dit getal. Staat het op 0,
-- dan kan de tweede regel uit mag_voor_speler() weg.
select 'spelers zonder account',
       (select count(*)::text from public.pool_members where user_id is null)
union all
select 'races in ' || public.controle_seizoen(),        (select count(*)::text from public.races where season = public.controle_seizoen())
union all
select 'races met deelnemerslijst',
       (select count(*)::text from public.races where season = public.controle_seizoen() and drivers is not null)
union all
-- Het getal waaraan je ziet of de sync zijn werk doet. Zonder deze regel stond
-- er wel hoeveel races er in de kalender staan, maar niet hoeveel er gereden
-- zijn -- en dat tweede is wat je wilt weten als je je afvraagt of de
-- uitslagen binnenkomen.
select 'races met uitslag',
       (select count(*)::text from public.races where season = public.controle_seizoen() and race_result is not null)
union all
select 'afgelaste races',
       (select count(*)::text from public.races where season = public.controle_seizoen() and afgelast)
union all
-- Rondt dit seizoen ooit af?
--
-- De seizoenslaag wordt pas gescoord als élke race een uitslag heeft of
-- afgelast is -- zie seizoenKlaar() in index.html, dat met dezelfde maatstaf
-- rekent. Blijft er één race hangen, dan levert die honderdvijftig punten
-- nooit iets op en blijft "Begin aan het volgende seizoen" grijs. Zonder deze
-- regel merk je dat pas in december.
select 'seizoen ' || public.controle_seizoen() || ' rond',
       case
         -- Zonder kalender is er niets om rond te zijn. "ok" zou hier gelden
         -- omdat er geen race is die tegenspreekt, en dat is precies het soort
         -- ok waar je niets aan hebt.
         when not exists (select 1 from public.races where season = public.controle_seizoen())
           then 'geen kalender'
         when not exists (
              select 1 from public.races r
              where r.season = public.controle_seizoen() and not r.afgelast
                and r.race_result is null
                and r.quali_result is null
                and r.sprint_result is null)
           then 'ok'
         else 'nog ' || (select count(*)::text from public.races r
              where r.season = public.controle_seizoen() and not r.afgelast
                and r.race_result is null
                and r.quali_result is null
                and r.sprint_result is null) || ' te gaan' end
union all
-- En het getal dat zegt of dat vanzelf goed komt. De sync zet een race die
-- OpenF1 een week na de deadline nog steeds niet heeft zelf op afgelast. Staat
-- hier iets anders dan nul, dan is dat niet gebeurd -- en dan blijft de race
-- voor iedereen op "wacht op uitslag" staan, wat niet te onderscheiden is van
-- een app die stuk is.
--
-- Mét de namen erbij, want op het moment dat hier iets staat wil je weten
-- wélke race en niet hoevéél. Zonder namen is de volgende stap "uitzoeken
-- welke", en dat is precies de stap waar je op afhaakt.
select 'blijven hangen (deadline > week geleden, niets binnen)',
       coalesce((
         select count(*)::text || ': ' || string_agg(r.name || ' (ronde ' || r.round || ')',
                                                     ', ' order by r.round)
         from public.races r
         where r.season = public.controle_seizoen() and not r.afgelast
           and r.race_result is null and r.quali_result is null and r.sprint_result is null
           and r.deadline_race is not null
           and r.deadline_race < now() - interval '7 days'
       ), '0')
union all
-- Alle zeven vlaggen. Er stonden er twee in, dus een met de hand ingevulde
-- sprint, snelste ronde, snelste pitstop, safety car of rode vlag telde als
-- nul -- terwijl dit juist de regel is die zegt "hier heeft iemand ingegrepen".
select 'handmatig ingevulde uitslagen',
       (select count(*)::text from public.races
        where season = public.controle_seizoen()
          and (quali_handmatig or race_handmatig or sprint_handmatig
               or fastest_lap_handmatig or fastest_pitstop_handmatig
               or safety_cars_handmatig or rode_vlag_handmatig))
union all
-- Niet op een aantal maar op namen: een telling van veertien zegt "ok" ook
-- als er één ontbreekt en er een andere bij staat, en hij gaat stilzwijgend
-- stuk zodra er een vraag bij komt. Dit zijn de vragen waar de presets in
-- index.html uit putten; ontbreekt er een, dan valt er in de app iets weg.
select 'vragen in de lijst',
       case when (select count(*) from public.questions
                  where id in ('quali_top10','race_top10','sprint_top10','winnaar','pole',
                               'snelste_ronde','snelste_pitstop','teamgenoot_duels',
                               'safety_cars','rode_vlag',
                               'kampioen','constructeur','winnaars','vierde_team')) = 14
       then 'ok'
       else 'incompleet: ' || (select count(*)::text from public.questions) || ' vragen' end
union all
-- Alleen wat élk weekend langskomt, net als weekendSom() in de app. De som
-- over álle vragen stond hier eerst, en die gaf na de sprint en de
-- seizoenslaag 377 -- een getal dat nergens op het scherm staat en achttien
-- weekenden per jaar niet klopt.
select 'punten per weekend: Simpel / Klassiek / Gevorderd',
       (select
          (select sum(punten)::text from public.questions
           where id in ('quali_top10','race_top10')) || ' / ' ||
          (select sum(punten)::text from public.questions
           where id in ('quali_top10','race_top10','winnaar','pole','snelste_ronde')) || ' / ' ||
          (select sum(punten)::text from public.questions
           where sessie in ('quali','race')))
union all
-- De twee die apart staan: de sprint komt op zes van de vierentwintig
-- weekenden langs en de seizoenslaag één keer per jaar.
select 'daarbovenop: sprint / seizoen',
       (select
          (select coalesce(sum(punten), 0)::text from public.questions
           where sessie = 'sprint') || ' / ' ||
          (select coalesce(sum(punten), 0)::text from public.questions
           where sessie = 'seizoen'))
union all
-- Wie de beheerpagina binnenlaat: het beheeradres, en wie er verder in
-- site_beheerders staat. Of het beheeradres al een bevestigd account heeft
-- staat erbij; zo niet, log dan één keer in op /beheer/ met Google.
-- Extra telt alleen andere accounts: een eerdere versie van dit bestand zette
-- het account van het beheeradres zelf ook in site_beheerders, en dat is
-- geen tweede beheerder.
select 'beheerders',
       public.beheer_adres()
       || case when exists (select 1 from auth.users
                            where lower(email) = public.beheer_adres()
                              and email_confirmed_at is not null)
               then ' (ingelogd)' else ' (nog nooit ingelogd)' end
       || coalesce((select ' + ' || count(*) || ' extra'
                    from public.site_beheerders b
                    left join auth.users u on u.id = b.user_id
                    where lower(coalesce(u.email, '')) <> public.beheer_adres()
                    having count(*) > 0), '')
union all
select 'winnaar ingevuld',
       (select count(*)::text from public.answers where question_id = 'winnaar')
union all
select 'ingevulde antwoorden',   (select count(*)::text from public.answers);

