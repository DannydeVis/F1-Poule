-- ------------------------------------------------------------
--  Controle
--  Hieronder moet overal 'ok' staan.
-- ------------------------------------------------------------

select 'unieke sleutel op predictions' as controle,
       case when exists (
         select 1 from pg_constraint
         where conrelid = 'public.predictions'::regclass
           and conname = 'predictions_uniek'
       ) then 'ok' else 'ONTBREEKT' end as uitkomst
union all
select 'deadline-trigger',
       case when exists (
         select 1 from pg_trigger
         where tgrelid = 'public.predictions'::regclass
           and tgname = 'predictions_deadline'
       ) then 'ok' else 'ONTBREEKT' end
union all
select 'deadline-trigger op answers',
       case when exists (
         select 1 from pg_trigger
         where tgrelid = 'public.answers'::regclass
           and tgname = 'answers_deadline'
       ) then 'ok' else 'ONTBREEKT' end
union all
select 'dubbele voorspellingen',
       case when (select count(*) from (
         select 1 from public.predictions
         group by pool_id, race_id, member_id having count(*) > 1) d) = 0
       then 'ok' else 'NOG AANWEZIG' end
union all
select 'aantal poules',        (select count(*)::text from public.pools)
union all
select 'aantal spelers',       (select count(*)::text from public.pool_members)
union all
select 'races in 2026',        (select count(*)::text from public.races where season = 2026)
union all
select 'races met deelnemerslijst',
       (select count(*)::text from public.races where season = 2026 and drivers is not null)
union all
select 'handmatig ingevulde uitslagen',
       (select count(*)::text from public.races
        where season = 2026 and (quali_handmatig or race_handmatig))
union all
select 'vragen in de lijst',
       case when (select count(*) from public.questions) = 9
       then 'ok' else (select count(*)::text from public.questions) end
union all
select 'punten Simpel / Klassiek / Gevorderd',
       (select
          (select sum(punten)::text from public.questions
           where id in ('quali_top10','race_top10')) || ' / ' ||
          (select sum(punten)::text from public.questions
           where id in ('quali_top10','race_top10','winnaar','pole','snelste_ronde')) || ' / ' ||
          (select sum(punten)::text from public.questions))
union all
select 'winnaar ingevuld',
       (select count(*)::text from public.answers where question_id = 'winnaar')
union all
select 'ingevulde antwoorden',   (select count(*)::text from public.answers)
union all
-- Blijft staan zolang niet zeker is dat alles goed is overgezet; de app
-- leest deze tabel niet meer.
select 'oude voorspellingen (ongebruikt)', (select count(*)::text from public.predictions);
