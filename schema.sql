-- ------------------------------------------------------------
--  Deadline
--  Dit is de enige regel die echt in de database wordt afgedwongen.
--
--  Belangrijk: er wordt op een *wijziging* getest, niet op de aanwezigheid
--  van de kolom. Anders kun je je race-top-10 niet meer opslaan zodra de
--  kwalificatie is begonnen, omdat het opslaan de ongewijzigde
--  kwalificatiekolom meestuurt.
-- ------------------------------------------------------------

create or replace function public.poule_deadline_bewaken()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  d_quali timestamptz;
  d_race  timestamptz;
begin
  select deadline_quali, deadline_race into d_quali, d_race
  from public.races where id = new.race_id;

  if not found then
    raise exception 'Race % bestaat niet', new.race_id;
  end if;

  if tg_op = 'INSERT' then
    if new.quali_top10 is not null and d_quali is not null and now() > d_quali then
      raise exception 'De kwalificatie van deze race is gesloten';
    end if;
    if (new.race_top10 is not null or new.race_winnaar is not null)
       and d_race is not null and now() > d_race then
      raise exception 'De race is gesloten';
    end if;
  else
    if new.quali_top10 is distinct from old.quali_top10
       and d_quali is not null and now() > d_quali then
      raise exception 'De kwalificatie van deze race is gesloten';
    end if;
    if (new.race_top10   is distinct from old.race_top10
        or new.race_winnaar is distinct from old.race_winnaar)
       and d_race is not null and now() > d_race then
      raise exception 'De race is gesloten';
    end if;
  end if;

  new.updated_at = now();
  return new;
end $$;

-- Dezelfde bewaking voor answers. De deadline is het enige wat hier hard in
-- de database is afgedwongen, dus die mag niet wegvallen doordat de app naar
-- een andere tabel schrijft. Welke deadline geldt hangt af van de vraag:
-- questions.sessie zegt of hij aan de kwalificatie of aan de race hangt.
-- Is het seizoen waar deze race bij hoort al begonnen? Dat is het moment
-- waarop de seizoensvragen vastliggen: de eerste sessie van ronde 1. `least`
-- slaat lege deadlines over, dus een weekend zonder sprint werkt gewoon.
create or replace function public.poule_seizoen_gestart(p_race_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(now() > least(r.deadline_sprint, r.deadline_quali, r.deadline_race), false)
  from public.races r where r.id = p_race_id;
$$;

-- En is het erop zit? Dan mag er niets meer bij, want dan is het antwoord
-- bekend. Dezelfde maatstaf als seizoenKlaar() in index.html: een race telt
-- als geweest zodra er van één sessie een uitslag is, en een afgelaste race
-- telt ook mee -- daar komt nooit meer iets van.
create or replace function public.poule_seizoen_voorbij(p_race_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select not exists (
    select 1 from public.races r
    where r.season = (select season from public.races where id = p_race_id)
      and not r.afgelast
      and r.race_result is null
      and r.quali_result is null
      and r.sprint_result is null
  );
$$;

create or replace function public.poule_antwoord_deadline()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  sessie_van text;
  deadline   timestamptz;
begin
  -- Weghalen. Dat liep hier eerst niet langs, en dat was een gat: wat je niet
  -- mag wijzigen kon je wél verwijderen en opnieuw invoeren. Alleen de
  -- seizoenslaag ligt vast; een gewoon antwoord mag gewoon weg.
  --
  -- Een cascade mag er altijd langs -- gaat de poule of de speler weg, dan
  -- horen de antwoorden mee. Zelfde uitzondering als bij de jokers, en op
  -- dezelfde manier te herkennen: een cascade zit een triggerlaag dieper dan
  -- een delete uit de app.
  if tg_op = 'DELETE' then
    if pg_trigger_depth() > 1 then return old; end if;
    select q.sessie into sessie_van from public.questions q where q.id = old.question_id;
    if sessie_van = 'seizoen' and public.poule_seizoen_gestart(old.race_id) then
      raise exception 'Je seizoensantwoord ligt vast zodra het seizoen begonnen is';
    end if;
    return old;
  end if;

  -- Een ongewijzigd antwoord opnieuw wegschrijven mag altijd; anders
  -- blokkeert een verstreken deadline het opslaan van een ándere vraag.
  if tg_op = 'UPDATE' and new.waarde is not distinct from old.waarde then
    new.updated_at = now();
    return new;
  end if;

  -- Kent de database deze vraag of race niet, dan weigeren de foreign keys
  -- de rij zo meteen zelf met een nette 23503, waar index.html een leesbare
  -- melding van maakt. Hier al een eigen fout gooien zou die overschaduwen.
  select q.sessie into sessie_van from public.questions q where q.id = new.question_id;
  if not found then return new; end if;

  -- Per sessie zijn eigen deadline. Stond als `case ... else deadline_race`,
  -- en dat betekende dat elke sessie die niet 'quali' heette stilletjes aan de
  -- race-deadline hing -- voor een sprint dus de verkeerde, en zonder dat
  -- iemand het zou merken.
  --
  -- De seizoenslaag hangt aan de éérste sessie van de race waar hij op staat.
  -- De app schrijft die antwoorden weg op ronde 1 van het seizoen, dus dit is
  -- precies "voordat er iets gereden is" -- en daarna nooit meer.
  select case sessie_van
           when 'quali'   then r.deadline_quali
           when 'sprint'  then r.deadline_sprint
           when 'seizoen' then least(r.deadline_sprint, r.deadline_quali, r.deadline_race)
           else                r.deadline_race
         end
    into deadline
  from public.races r where r.id = new.race_id;
  if not found then return new; end if;

  -- De seizoenslaag heeft zijn eigen regel, en die is losser dan een deadline.
  --
  -- Eerst gold: vóór de eerste race wel, daarna nooit meer. Dat sluit iedereen
  -- buiten die halverwege instapt -- en die heeft de gemiste races al als
  -- achterstand; honderdvijftig punten die hij onmogelijk kon halen is een
  -- tweede straf voor hetzelfde.
  --
  -- Nu geldt de streep per antwoord in plaats van per seizoen: invullen mag
  -- zolang het seizoen loopt, maar wat er eenmaal staat ligt vast. Eén schot,
  -- wanneer je ook binnenkomt. Zie BEDIENING.md §6d.
  if sessie_van = 'seizoen' and public.poule_seizoen_gestart(new.race_id) then
    if tg_op = 'UPDATE' then
      raise exception 'Je seizoensantwoord ligt vast zodra het seizoen begonnen is';
    end if;
    if public.poule_seizoen_voorbij(new.race_id) then
      raise exception 'Het seizoen is voorbij, de seizoensvragen zijn gescoord';
    end if;
    new.updated_at = now();
    return new;
  end if;

  if deadline is not null and now() > deadline then
    if sessie_van = 'quali' then
      raise exception 'De kwalificatie van deze race is gesloten';
    elsif sessie_van = 'sprint' then
      raise exception 'De sprint van deze race is gesloten';
    elsif sessie_van = 'seizoen' then
      raise exception 'Het seizoen is al begonnen, de seizoensvragen liggen vast';
    else
      raise exception 'De race is gesloten';
    end if;
  end if;

  new.updated_at = now();
  return new;
end $$;

drop trigger if exists answers_deadline on public.answers;
create trigger answers_deadline
  before insert or update or delete on public.answers
  for each row execute function public.poule_antwoord_deadline();

-- ------------------------------------------------------------
--  Jokers
--  Eén tot vijf per seizoen (de poule kiest), één per weekend, en alleen
--  zolang dat weekend nog
--  helemaal openstaat. Dit is de tweede regel die hard in de database zit,
--  en om dezelfde reden als de deadline: een joker die je achteraf mag
--  verzetten is geen keuze maar een knop om de uitslag mee te herschrijven.
-- ------------------------------------------------------------

create or replace function public.poule_joker_bewaken()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  rij      public.jokers;
  vanaf    timestamptz;
  eerste   timestamptz;
  seizoen  int;
  gezet    int;
  mag      int;
begin
  rij := coalesce(new, old);

  -- Een joker die meegaat omdat zijn poule, zijn speler of zijn race weggaat
  -- is geen speler die van gedachten verandert. Zo'n rij komt hier binnen via
  -- een cascade, en dat is aan pg_trigger_depth() te zien: die staat op 1 als
  -- de app zelf schrijft en hoger zodra een andere trigger ons aanroept.
  -- Zonder deze regel zou "verwijder mijn account" vastlopen op een joker die
  -- op een gereden weekend ligt, en dat is precies het soort deur dat niet op
  -- slot hoort te zitten.
  if tg_op = 'DELETE' and pg_trigger_depth() > 1 then return old; end if;

  -- Staat de regel uit in deze poule, dan bestaat een joker hier niet.
  select p.jokers_vanaf into vanaf from public.pools p where p.id = rij.pool_id;
  if not found then return rij; end if;   -- de foreign key klaagt zo zelf
  if vanaf is null then
    raise exception 'Jokers staan in deze poule niet aan';
  end if;

  -- De eerste deadline van het weekend, wat die sessie ook is. Op een
  -- sprintweekend is dat de sprint en niet de kwalificatie, dus dit mag geen
  -- vaste kolom zijn.
  select least(r.deadline_sprint, r.deadline_quali, r.deadline_race), r.season
    into eerste, seizoen
  from public.races r where r.id = rij.race_id;
  if not found then return rij; end if;

  if eerste is not null and now() > eerste then
    raise exception 'Dit weekend is al begonnen, je joker ligt vast';
  end if;
  -- Niet met terugwerkende kracht: een weekend dat al liep toen de poulebaas
  -- de regel aanzette telt niet mee. Zelfde streep als bij automatisch
  -- invullen.
  if eerste is not null and eerste < vanaf then
    raise exception 'Dit weekend liep al toen de jokers aangezet werden';
  end if;

  if tg_op = 'DELETE' then return old; end if;

  -- Zoveel als deze poule er geeft. De rij zelf niet meetellen, anders kun je
  -- een bestaande joker niet meer opnieuw wegschrijven.
  select p.jokers_aantal into mag from public.pools p where p.id = new.pool_id;
  select count(*) into gezet
  from public.jokers j join public.races r on r.id = j.race_id
  where j.pool_id = new.pool_id and j.member_id = new.member_id
    and r.season = seizoen and j.race_id <> new.race_id;
  if gezet >= mag then
    raise exception 'Je hebt je % jokers voor dit seizoen al gezet', mag;
  end if;

  return new;
end $$;

-- Het aantal omlaag zetten mag niet ónder wat er al ligt.
--
-- Zonder deze regel zet de poulebaas het op 1 terwijl drie mensen er vier
-- hebben liggen, en dan klopt er niets meer: jokersOver() in de app gaat
-- negatief, en "je hebt je 1 jokers al gezet" slaat nergens op bij iemand die
-- er vier heeft. Omhoog mag altijd -- iedereen krijgt er evenveel bij.
create or replace function public.poule_jokeraantal_bewaken()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare hoogst int;
begin
  if new.jokers_aantal = old.jokers_aantal then return new; end if;
  select coalesce(max(t.aantal), 0) into hoogst from (
    select count(*) as aantal
    from public.jokers j join public.races r on r.id = j.race_id
    where j.pool_id = new.id and r.season = new.season
    group by j.member_id) t;
  if new.jokers_aantal < hoogst then
    raise exception 'Er ligt al iemand met % jokers, dus % kan niet', hoogst, new.jokers_aantal;
  end if;
  return new;
end $$;

drop trigger if exists pools_jokeraantal on public.pools;
create trigger pools_jokeraantal
  before update on public.pools
  for each row execute function public.poule_jokeraantal_bewaken();

