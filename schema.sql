-- ------------------------------------------------------------
--  Deadline
--  Dit is de enige regel die echt in de database wordt afgedwongen.
--
--  Belangrijk: er wordt op een *wijziging* getest, niet op de aanwezigheid
--  van de kolom. Anders kun je je race-top-10 niet meer opslaan zodra de
--  kwalificatie is begonnen, omdat het opslaan de ongewijzigde
--  kwalificatiekolom meestuurt.
-- ------------------------------------------------------------

create or replace function public.poule_deadline_bewaken()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  d_quali timestamptz;
  d_race  timestamptz;
begin
  select deadline_quali, deadline_race into d_quali, d_race
  from public.races where id = new.race_id;

  if not found then
    raise exception 'Race % bestaat niet', new.race_id;
  end if;

  if tg_op = 'INSERT' then
    if new.quali_top10 is not null and d_quali is not null and now() > d_quali then
      raise exception 'De kwalificatie van deze race is gesloten';
    end if;
    if (new.race_top10 is not null or new.race_winnaar is not null)
       and d_race is not null and now() > d_race then
      raise exception 'De race is gesloten';
    end if;
  else
    if new.quali_top10 is distinct from old.quali_top10
       and d_quali is not null and now() > d_quali then
      raise exception 'De kwalificatie van deze race is gesloten';
    end if;
    if (new.race_top10   is distinct from old.race_top10
        or new.race_winnaar is distinct from old.race_winnaar)
       and d_race is not null and now() > d_race then
      raise exception 'De race is gesloten';
    end if;
  end if;

  new.updated_at = now();
  return new;
end $$;

drop trigger if exists predictions_deadline on public.predictions;
create trigger predictions_deadline
  before insert or update on public.predictions
  for each row execute function public.poule_deadline_bewaken();

-- Dezelfde bewaking voor answers. De deadline is het enige wat hier hard in
-- de database is afgedwongen, dus die mag niet wegvallen doordat de app naar
-- een andere tabel schrijft. Welke deadline geldt hangt af van de vraag:
-- questions.sessie zegt of hij aan de kwalificatie of aan de race hangt.
create or replace function public.poule_antwoord_deadline()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  sessie_van text;
  deadline   timestamptz;
begin
  -- Een ongewijzigd antwoord opnieuw wegschrijven mag altijd; anders
  -- blokkeert een verstreken deadline het opslaan van een ándere vraag.
  if tg_op = 'UPDATE' and new.waarde is not distinct from old.waarde then
    new.updated_at = now();
    return new;
  end if;

  -- Kent de database deze vraag of race niet, dan weigeren de foreign keys
  -- de rij zo meteen zelf met een nette 23503, waar index.html een leesbare
  -- melding van maakt. Hier al een eigen fout gooien zou die overschaduwen.
  select q.sessie into sessie_van from public.questions q where q.id = new.question_id;
  if not found then return new; end if;

  select case when sessie_van = 'quali' then r.deadline_quali else r.deadline_race end
    into deadline
  from public.races r where r.id = new.race_id;
  if not found then return new; end if;

  if deadline is not null and now() > deadline then
    if sessie_van = 'quali' then
      raise exception 'De kwalificatie van deze race is gesloten';
    else
      raise exception 'De race is gesloten';
    end if;
  end if;

  new.updated_at = now();
  return new;
end $$;

drop trigger if exists answers_deadline on public.answers;
create trigger answers_deadline
  before insert or update on public.answers
  for each row execute function public.poule_antwoord_deadline();

