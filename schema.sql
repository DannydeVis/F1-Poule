-- ---- poules -------------------------------------------------
-- Lezen stond op `true`, en dat was het gat: met de publieke anon key was
-- élke poule in de database op te vragen. Nu alleen wat je zonder sleutel
-- ook hoort te zien — de poules waar je zelf in zit, en de poules die
-- uitdrukkelijk openbaar zijn. Binnenkomen met een code of een id loopt via
-- poule_ophalen(); zie de uitleg daarboven voor waarom dat een functie moet
-- zijn en geen policy.
create policy pools_lezen on public.pools
  for select to anon, authenticated
  using (is_public or public.is_member(id));
create policy pools_aanmaken on public.pools
  for insert to anon, authenticated with check (true);
-- Alleen de poulebaas past de omschrijving of de vragenset aan. Let op de
-- volgorde bij het aanmaken: eerst de poule (nog zonder eigenaar), dan de
-- speler, dan pas deze update — op dat moment is de eigenaar nog leeg en ben
-- je al lid, dus mag_beheren() zegt ja.
create policy pools_bijwerken on public.pools
  for update to anon, authenticated
  using (public.mag_beheren(id)) with check (public.mag_beheren(id));
-- Geen policy voor delete: de app verwijdert nooit een poule, dus die deur
-- hoeft niet open te staan.

-- ---- spelers ------------------------------------------------
-- Je eigen spelers (daarmee vind je na het inloggen je poules terug), en de
-- medespelers in een poule waar je zelf in zit. Het "Wie ben jij?"-scherm
-- komt langs poule_ophalen(), want daar ben je nog geen lid.
create policy pool_members_lezen on public.pool_members
  for select to anon, authenticated
  using (user_id = auth.uid() or public.is_member(pool_id));
-- Meedoen mag, maar nooit namens een ander account.
create policy pool_members_meedoen on public.pool_members
  for insert to anon, authenticated
  with check (user_id is null or user_id = auth.uid());
-- Dit is de kern van het claimen. `using` bepaalt welke rijen je mag aanraken,
-- `with check` hoe ze eruit mogen komen:
--
--   * een speler die van niemand is  -> claimen mag
--   * je eigen speler                -> loslaten mag
--   * de speler van een ander        -> niets
--
-- En de poulebaas mag een speler losmaken van het account waar hij per
-- ongeluk aan is blijven hangen. Zonder die uitweg is één misklik op het
-- "Wie ben jij?"-scherm genoeg om iemands seizoen onbereikbaar te maken.
create policy pool_members_bijwerken on public.pool_members
  for update to anon, authenticated
  using (user_id is null or user_id = auth.uid() or public.mag_beheren(pool_id))
  with check (user_id is null or user_id = auth.uid() or public.mag_beheren(pool_id));

-- ---- races en vragen ----------------------------------------
-- races is de enige tabel die door álle poules gedeeld wordt: één rij per
-- race per seizoen, geen pool_id. Wie hier schreef, veranderde de uitslag
-- voor iedereen die dit seizoen volgt. Alleen lezen dus; schrijven doet de
-- sync op een GitHub-runner met de service_role key, en die gaat overal
-- langs, ook langs RLS.
create policy races_lezen on public.races
  for select to anon, authenticated using (true);
-- De vragenlijst hoort uit dit bestand te komen, niet uit de app.
create policy questions_lezen on public.questions
  for select to anon, authenticated using (true);

-- ---- welke vragen doet deze poule -------------------------
create policy pool_questions_lezen on public.pool_questions
  for select to anon, authenticated using (public.is_member(pool_id));
create policy pool_questions_beheren on public.pool_questions
  for all to anon, authenticated
  using (public.mag_beheren(pool_id)) with check (public.mag_beheren(pool_id));

-- ---- de inzendingen zelf ------------------------------------
-- Binnen je eigen poule mag je alles zien: de app laat je na de deadline
-- elkaars top 10 zien en de stand telt iedereen mee. Daarbuiten niets, en
-- dat is het verschil met hoe dit stond.
create policy answers_lezen on public.answers
  for select to anon, authenticated using (public.is_member(pool_id));
-- Schrijven alleen voor je eigen speler. `for all` dekt insert, update én
-- delete in één keer, en dat is precies wat een upsert nodig heeft: PostgREST
-- maakt daar insert ... on conflict do update van.
create policy answers_eigen on public.answers
  for all to anon, authenticated
  using (public.mag_voor_speler(member_id))
  with check (public.mag_voor_speler(member_id));

-- ---- jokers -------------------------------------------------
-- Dezelfde afspraak als bij de antwoorden: binnen je poule zie je ze
-- allemaal (anders klopt de stand niet en weet je niet wie zijn joker waar
-- neerlegt), erbuiten niets. Schrijven alleen voor je eigen speler.
create policy jokers_lezen on public.jokers
  for select to anon, authenticated using (public.is_member(pool_id));
create policy jokers_eigen on public.jokers
  for all to anon, authenticated
  using (public.mag_voor_speler(member_id))
  with check (public.mag_voor_speler(member_id));

-- ---- waar een melding naartoe mag ---------------------------
-- Anders dan bij de jokers: hier is er geen lezen-voor-je-medespelers. Een
-- abonnement zegt iets over iemands toestel en niemand in de poule heeft dat
-- nodig. Alleen je eigen rijen, in allebei de richtingen. De sync leest ze met
-- de service_role key en gaat overal langs.
create policy push_eigen on public.push_abonnementen
  for all to anon, authenticated
  using (public.mag_voor_speler(member_id))
  with check (public.mag_voor_speler(member_id));

-- ------------------------------------------------------------
--  Rechten op tabelniveau
--  Supabase geeft anon en authenticated standaard alles op `public`. Dat is
--  een blanco cheque die nergens in dit bestand te zien was, dus staat hij er
--  nu expliciet — met twee voordelen. Je leest hier wat er mag, en de CI doet
--  het na: daar hadden anon en authenticated tot nu toe hélemaal geen rechten,
--  waardoor de policies hierboven wel bestonden maar nooit uitgeoefend werden.
--
--  Dit is een tweede slot naast RLS. Een policy die per ongeluk te ruim wordt
--  komt hier alsnog niet langs.
-- ------------------------------------------------------------

grant usage on schema public to anon, authenticated;

grant select, insert, update, delete on public.pools          to anon, authenticated;
-- pool_members is de enige tabel met een kolomgrens erin. Lezen mag op alles
-- behalve profiel_code en profiel: die eerste is de link naar je publieke
-- pagina, en die deel je zelf of niet -- ook niet met je medespelers. RLS werkt
-- per rij en kan dat onderscheid niet maken, een grant per kolom wel.
--
-- Je eigen code krijg je gewoon te zien: poule_ophalen() geeft hem mee voor de
-- rijen die aan jouw account hangen, en die functie is security definer en gaat
-- hier dus langs.
grant insert, update, delete on public.pool_members to anon, authenticated;
revoke select on public.pool_members from anon, authenticated;
grant select (member_id, pool_id, display_name, user_id, created_at)
  on public.pool_members to anon, authenticated;
grant select, insert, update, delete on public.pool_questions to anon, authenticated;
grant select, insert, update, delete on public.answers        to anon, authenticated;
grant select, insert, update, delete on public.jokers         to anon, authenticated;
grant select, insert, update, delete on public.push_abonnementen to anon, authenticated;
grant select on public.questions to anon, authenticated;

-- races is het strengst, en met opzet: één tabel voor alle poules, dus wie
-- hier schrijft raakt iedereen. Alleen de sync schrijft, en die draait op een
-- runner met de service_role key — die gaat langs zowel de grant als RLS.
grant select on public.races to anon, authenticated;
revoke insert, update, delete on public.races from anon, authenticated;

grant usage on all sequences in schema public to anon, authenticated;

-- ------------------------------------------------------------
--  Beheer
--
--  De beheerpagina (beheer/index.html) is voor wie de hele site onderhoudt:
--  alle poules, alle spelers, de data van OpenF1, of de sync draait, en de
--  statistieken. Dat is meer dan welke speler of poulebaas ook mag zien, dus
--  het loopt nergens via de tabellen zelf. Alles gaat via de functies
--  hieronder, security definer, en elke functie begint met dezelfde vraag:
--  ben jij beheerder? Zo niet, dan een fout en geen lege uitkomst.
--
--  De service_role key komt er niet aan te pas. Die staat alleen als geheim
--  bij GitHub, voor de sync. De beheerpagina gebruikt dezelfde publieke anon
--  key als de app, met het account waarmee je bent ingelogd.
-- ------------------------------------------------------------

-- Wie beheerder is. Zonder policies: via de API is deze tabel voor niemand
-- te lezen of te schrijven. Iemand toevoegen gaat in de SQL editor.
create table if not exists public.site_beheerders (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  toegevoegd timestamptz not null default now()
);
alter table public.site_beheerders enable row level security;
revoke all on public.site_beheerders from anon, authenticated;

-- Het beheeradres: het contactadres uit de privacyverklaring. Elk account met
-- dit adres is beheerder, zodra het adres bevestigd is -- een Google-account
-- met dit adres, of een mailadres waarvan de inloglink is aangeklikt. Wie het
-- adres niet in handen heeft komt er dus niet in, ook niet door het ergens in
-- te tikken. En het hangt niet af van wanneer dit bestand gedraaid is: log in,
-- op welk toestel ook, en je bent binnen. Meer beheerders gaan in
-- site_beheerders (zie BEDIENING.md §16).
create or replace function public.beheer_adres()
returns text
language sql
immutable
as $$ select 'devisser.danny@gmail.com'::text $$;

create or replace function public.ik_ben_beheerder()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() is not null and (
    exists (select 1 from public.site_beheerders where user_id = auth.uid())
    or exists (select 1 from auth.users u
               where u.id = auth.uid()
                 and lower(u.email) = public.beheer_adres()
                 and u.email_confirmed_at is not null));
$$;
revoke all on function public.ik_ben_beheerder() from public;
grant execute on function public.ik_ben_beheerder() to anon, authenticated;

-- De deur. Elke beheerfunctie roept hem als eerste aan.
create or replace function public.beheer_poort()
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.ik_ben_beheerder() then
    raise exception 'Alleen voor beheerders' using errcode = '42501';
  end if;
end $$;
