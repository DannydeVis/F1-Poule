-- Een poule aanpassen: naam, omschrijving, openbaar, poulebaas. Alleen de
-- sleutels die in p_wijziging staan veranderen.
create or replace function public.beheer_poule_bijwerken(p_pool uuid, p_wijziging jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  baas uuid;
begin
  perform public.beheer_poort();
  if not exists (select 1 from public.pools where id = p_pool) then
    raise exception 'Die poule bestaat niet';
  end if;
  if p_wijziging ? 'name' then
    if length(trim(coalesce(p_wijziging ->> 'name', ''))) = 0 then
      raise exception 'Een poule heeft een naam nodig';
    end if;
    update public.pools set name = trim(p_wijziging ->> 'name') where id = p_pool;
  end if;
  if p_wijziging ? 'beschrijving' then
    update public.pools set beschrijving = nullif(trim(coalesce(p_wijziging ->> 'beschrijving', '')), '')
    where id = p_pool;
  end if;
  if p_wijziging ? 'is_public' then
    update public.pools set is_public = coalesce((p_wijziging ->> 'is_public')::boolean, false)
    where id = p_pool;
  end if;
  if p_wijziging ? 'owner_member_id' then
    baas := nullif(p_wijziging ->> 'owner_member_id', '')::uuid;
    if baas is not null and not exists (
        select 1 from public.pool_members where member_id = baas and pool_id = p_pool) then
      raise exception 'Die speler zit niet in deze poule';
    end if;
    update public.pools set owner_member_id = baas where id = p_pool;
  end if;
  return (select to_jsonb(p) from public.pools p where id = p_pool);
end $$;

