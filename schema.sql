-- De reeksen voor de grafieken op de beheerpagina.
create or replace function public.beheer_statistieken()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  seizoen int := public.controle_seizoen();
begin
  perform public.beheer_poort();
  return jsonb_build_object(
    'seizoen', seizoen,
    -- Nieuwe spelers en poules per week, het afgelopen halfjaar.
    'spelers_per_week', coalesce((
      select jsonb_agg(jsonb_build_object('week', w, 'aantal', n) order by w)
      from (select date_trunc('week', created_at)::date w, count(*) n
            from public.pool_members where created_at > now() - interval '26 weeks'
            group by 1) x), '[]'::jsonb),
    'poules_per_week', coalesce((
      select jsonb_agg(jsonb_build_object('week', w, 'aantal', n) order by w)
      from (select date_trunc('week', created_at)::date w, count(*) n
            from public.pools where created_at > now() - interval '26 weeks'
            group by 1) x), '[]'::jsonb),
    -- Elke dag van de afgelopen dertig, ook de dagen zonder bezoek.
    'bezoeken_per_dag', (
      select jsonb_agg(jsonb_build_object(
               'dag', d::date,
               'bezoeken', coalesce((select sum(aantal) from public.bezoeken b where b.dag = d::date), 0),
               'actief', (select count(*) from public.actief a where a.dag = d::date))
             order by d)
      from generate_series(current_date - 29, current_date, interval '1 day') d),
    -- Per race van dit seizoen: hoeveel spelers er iets inleverden, tegen
    -- hoeveel er toen in een poule van dit seizoen zaten. De seizoensvragen
    -- tellen niet mee: die hangen aan de eerste race en zouden die opblazen.
    'inzendingen_per_race', coalesce((
      select jsonb_agg(jsonb_build_object(
               'race_id', r.id, 'ronde', r.round, 'naam', r.name,
               'inzenders', (select count(distinct a.member_id) from public.answers a
                              join public.questions q on q.id = a.question_id
                             where a.race_id = r.id and q.sessie <> 'seizoen'),
               'spelers', (select count(*) from public.pool_members m
                             join public.pools p on p.id = m.pool_id
                            where p.season = r.season
                              and m.created_at <= coalesce(r.deadline_race, now())))
             order by r.round)
      from public.races r
      where r.season = seizoen
        and coalesce(least(r.deadline_sprint, r.deadline_quali, r.deadline_race), now()) < now() + interval '7 days'),
      '[]'::jsonb),
    -- Wat voor accounts er achter de spelers zitten.
    'accounts', coalesce((
      select jsonb_object_agg(soort, n)
      from (select public.beheer_accountsoort(m.user_id) soort, count(*) n
            from public.pool_members m group by 1) x), '{}'::jsonb)
  );
end $$;

