-- Een lijst coureurnummers uit jsonb, of null. Hooguit dertig: meer rijdt er
-- niet mee, en meer is een vergissing.
create or replace function public.beheer_lijst(p_waarde jsonb)
returns text[]
language plpgsql
immutable
set search_path = public
as $$
declare
  lijst text[];
begin
  if p_waarde is null or jsonb_typeof(p_waarde) = 'null' then return null; end if;
  if jsonb_typeof(p_waarde) <> 'array' then raise exception 'Een uitslag is een lijst'; end if;
  select array_agg(x) into lijst from jsonb_array_elements_text(p_waarde) x;
  if coalesce(array_length(lijst, 1), 0) = 0 then return null; end if;
  if array_length(lijst, 1) > 30 then raise exception 'Een uitslag heeft hooguit dertig plekken'; end if;
  return lijst;
end $$;
revoke all on function public.beheer_lijst(jsonb) from public;

-- Een race bijstellen. Twee dingen die de sync niet zelf kan beslissen:
--
--   afgelast        een race die niet doorgaat telt voor niemand mee;
--   *_result        een uitslag overnemen (uit de vergelijking met OpenF1 op
--                   de beheerpagina) of leegmaken. Leeg haalt de sync hem de
--                   volgende ronde opnieuw op. De handmatig-vlag gaat mee met
--                   `handmatig`: een uitslag die van OpenF1 komt is niet met
--                   de hand, en die mag de sync later nog verbeteren (een
--                   straf achteraf).
create or replace function public.beheer_race_bijwerken(p_race bigint, p_wijziging jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  hand boolean := coalesce((p_wijziging ->> 'handmatig')::boolean, false);
begin
  perform public.beheer_poort();
  if not exists (select 1 from public.races where id = p_race) then
    raise exception 'Die race bestaat niet';
  end if;
  if p_wijziging ? 'afgelast' then
    update public.races set afgelast = coalesce((p_wijziging ->> 'afgelast')::boolean, false)
    where id = p_race;
  end if;
  if p_wijziging ? 'quali_result' then
    update public.races set quali_result = public.beheer_lijst(p_wijziging -> 'quali_result'),
                            quali_handmatig = hand and p_wijziging -> 'quali_result' <> 'null'::jsonb
    where id = p_race;
  end if;
  if p_wijziging ? 'race_result' then
    update public.races set race_result = public.beheer_lijst(p_wijziging -> 'race_result'),
                            race_handmatig = hand and p_wijziging -> 'race_result' <> 'null'::jsonb
    where id = p_race;
  end if;
  if p_wijziging ? 'sprint_result' then
    update public.races set sprint_result = public.beheer_lijst(p_wijziging -> 'sprint_result'),
                            sprint_handmatig = hand and p_wijziging -> 'sprint_result' <> 'null'::jsonb
    where id = p_race;
  end if;
  return (select to_jsonb(r) from public.races r where id = p_race);
end $$;

