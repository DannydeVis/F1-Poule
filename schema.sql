-- ============================================================
--  F1 Poule — databaseschema
--  Plak dit in de Supabase SQL editor en draai het.
--
--  Het script is opnieuw te draaien op een bestaande database. Het maakt
--  ontbrekende tabellen en kolommen aan, herstelt de sleutels en policies,
--  en laat onderaan zien of alles klopt. Bestaande voorspellingen blijven
--  staan; alleen rijen die de app toch niet kan tonen (exacte dubbelen en
--  rijen zonder speler of race) worden opgeruimd, met een melding erbij.
--
--  Werkt het daarna nog niet, dan wijkt de oude tabelstructuur te ver af.
--  Draai in dat geval eerst reset.sql en daarna dit bestand opnieuw.
-- ============================================================

create extension if not exists pgcrypto;

-- ------------------------------------------------------------
--  Tabellen
-- ------------------------------------------------------------

create table if not exists public.pools (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  -- Een regel over waar deze poule voor is: "met de collega's, om de eer".
  beschrijving text,
  season     int  not null default 2026,
  join_code  text not null unique default upper(substr(md5(random()::text), 1, 6)),
  created_at timestamptz not null default now()
);

create table if not exists public.pool_members (
  member_id    uuid primary key default gen_random_uuid(),
  pool_id      uuid not null,
  display_name text not null,
  -- Welk account bij deze speler hoort. Leeg zolang niemand hem geclaimd
  -- heeft: de app werkte lang zonder login, en die spelers bestaan nog.
  -- `on delete cascade` is er voor "verwijder mijn account": één rij weg uit
  -- auth.users en al je spelers gaan mee.
  user_id      uuid references auth.users(id) on delete cascade,
  created_at   timestamptz not null default now()
);

create table if not exists public.races (
  id             bigint generated by default as identity primary key,
  season         int  not null,
  round          int  not null,
  name           text not null,
  country        text,
  race_key       bigint,
  quali_key      bigint,
  deadline_quali timestamptz,
  deadline_race  timestamptz,
  drivers        jsonb,
  quali_result   text[],
  race_result    text[],
  -- Met de hand ingevoerd in plaats van opgehaald bij OpenF1. De sync vult
  -- alleen lege uitslagen, dus zo'n uitslag wordt nooit meer automatisch
  -- gecorrigeerd; daarom moet zichtbaar zijn welke het zijn.
  quali_handmatig boolean not null default false,
  race_handmatig  boolean not null default false,
  -- Losse uitslagen: één coureurnummer per stuk.
  fastest_lap               text,
  fastest_pitstop           text,
  fastest_lap_handmatig     boolean not null default false,
  fastest_pitstop_handmatig boolean not null default false,
  -- Twee uitslagen die niets met een coureur te maken hebben.
  safety_cars               int,
  rode_vlag                 boolean,
  -- Een race die niet doorgegaan is. Hij blijft in de kalender staan omdat
  -- mensen er al iets voor ingevuld kunnen hebben, maar hij scoort niet en
  -- hij hoort niet eeuwig op "wacht op uitslag" te blijven staan.
  afgelast                  boolean not null default false,
  safety_cars_handmatig     boolean not null default false,
  rode_vlag_handmatig       boolean not null default false
);

-- ------------------------------------------------------------
--  Vragen
--  Zie BEDIENING.md. Vaste kolommen werken tot een stuk of drie vragen;
--  daarboven is een rij per vraag eenvoudiger, en pas dan kan een poule
--  zelf kiezen wat er meedoet.
--
--  De app leest en schrijft deze tabellen sinds de migratie.
-- ------------------------------------------------------------

create table if not exists public.questions (
  id       text primary key,   -- 'quali_top10', 'winnaar', ...
  naam     text not null,
  punten   int  not null,      -- maximaal haalbaar per weekend
  sessie   text not null,      -- 'quali' of 'race': aan welke deadline hij hangt
  soort    text not null,      -- 'top10' | 'coureur' | 'getal' | 'janee' | 'duels'
  -- Gokvragen scoren hoog per stuk maar hangen van geluk af. BEDIENING.md §8
  -- wil waarschuwen zodra ze samen boven 30% van het maximum uitkomen, en
  -- daarvoor moet ergens vastliggen wélke dat zijn.
  gok      boolean not null default false,
  volgorde int  not null default 0
);

-- Welke vragen doen mee in een poule. Aanwezig = aan; dat scheelt een
-- boolean die altijd op true zou staan.
create table if not exists public.pool_questions (
  pool_id     uuid not null,
  question_id text not null,
  primary key (pool_id, question_id)
);

-- Eén rij per ingevulde vraag, in plaats van een kolom per vraagsoort.
-- waarde is jsonb omdat een top 10 een lijst is, een winnaar een tekst,
-- het aantal safety cars een getal en de rode vlag een ja of nee.
create table if not exists public.answers (
  pool_id     uuid   not null,
  race_id     bigint not null,
  member_id   uuid   not null,
  question_id text   not null,
  waarde      jsonb  not null,
  updated_at  timestamptz not null default now(),
  primary key (pool_id, race_id, member_id, question_id)
);

-- Vijf keer per seizoen mag je één weekend dubbel laten tellen. Een eigen
-- tabel en geen kolom op answers, want een joker hangt aan het wéékend en
-- niet aan één vraag: je zet hem op Monza, niet op de top 10 van Monza.
-- Bestaat de rij, dan staat de joker; hem weghalen is de rij verwijderen.
create table if not exists public.jokers (
  pool_id   uuid   not null,
  race_id   bigint not null,
  member_id uuid   not null,
  gezet_op  timestamptz not null default now(),
  primary key (pool_id, race_id, member_id)
);

-- Waar een melding naartoe mag. Eén rij per toestel per speler: dezelfde
-- speler op een telefoon en een laptop heeft twee abonnementen, en elk
-- abonnement heeft zijn eigen sleutels. endpoint is de primaire sleutel omdat
-- de pushdienst hem uitdeelt en garandeert dat hij uniek is.
--
-- Wat hier staat is niet gevoelig op zichzelf -- je kunt er geen melding mee
-- lezen -- maar wel een aanwijzing over welk toestel iemand gebruikt. Dus
-- staat het achter dezelfde muur als de rest: alleen je eigen rijen.
create table if not exists public.push_abonnementen (
  endpoint   text   not null primary key,
  member_id  uuid   not null,
  pool_id    uuid   not null,
  p256dh     text   not null,
  auth       text   not null,
  created_at timestamptz not null default now(),
  -- Waar de laatste melding over ging. Voorkomt dat de sync elk uur opnieuw
  -- dezelfde herinnering stuurt: hij schrijft hier wat hij verstuurde en slaat
  -- het de volgende ronde over.
  laatst     text,
  -- In welke taal de melding moet. De app vertaalt zichzelf in de browser,
  -- maar een push komt uit scripts/sync.mjs en die heeft geen browser -- dus
  -- moet de keuze hier staan. Per abonnement en niet per speler: dezelfde
  -- persoon kan zijn telefoon op Engels en zijn laptop op Nederlands hebben.
  taal       text not null default 'nl'
);

